async function seed() {
  try {
    await mongoose.connect(process.env.MONGO_URI);
    console.log("✅ Connected to MongoDB");

    let leadsUpserted = 0;
    let leadsModified = 0;

    for (const customer of autogateCustomers) {
      const doc = customerToLead(customer);
      const result = await Lead.updateOne(
        { autogateId: customer.autogateId },
        { $set: doc },
        { upsert: true }
      );
      if (result.upsertedCount) leadsUpserted++;
      else if (result.modifiedCount) leadsModified++;
    }

    let invUpserted = 0;
    let invModified = 0;

    for (const item of autogateInventory) {
      const doc = inventoryItemToDoc(item);
      const result = await Inventory.updateOne(
        { identifier: item.identifier },
        { $set: doc },
        { upsert: true }
      );
      if (result.upsertedCount) invUpserted++;
      else if (result.modifiedCount) invModified++;
    }

    console.log("\n🌱 Autogate import complete:");
    console.log(`   Leads    → ${leadsUpserted} inserted, ${leadsModified} updated`);
    console.log(`   Inventory → ${invUpserted} inserted, ${invModified} updated`);
    console.log(`\n   Total inventory in DB (autogate): ${autogateInventory.length} records`);
    process.exit(0);
  } catch (err) {
    console.error("❌ Import failed:", err.message);
    process.exit(1);
  }
}

seed();
